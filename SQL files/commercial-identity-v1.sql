-- Protected read interface uses the existing transaction-bound, signed RLS identity.
CREATE FUNCTION business_management.is_business_owner() RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,public,app_security AS $$
 SELECT EXISTS(SELECT 1 FROM public.business_owner WHERE account_id=app_security.actor_customer_id() AND enabled)
$$;
REVOKE ALL ON FUNCTION business_management.is_business_owner() FROM PUBLIC;
CREATE FUNCTION business_management.business_stores() RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=pg_catalog,public,app_security AS $$
BEGIN
 IF NOT business_management.is_business_owner() THEN RAISE EXCEPTION 'Business Owner required' USING ERRCODE='42501'; END IF;
 RETURN jsonb_build_object('business',(SELECT to_jsonb(b) FROM public.business b),
   'stores',COALESCE((SELECT jsonb_agg(to_jsonb(s) ORDER BY s.branch_id) FROM public.branch s),'[]'::jsonb));
END $$;
REVOKE ALL ON FUNCTION business_management.business_stores() FROM PUBLIC;
DO $$ DECLARE runtime text:=current_setting('app.runtime_role'); BEGIN
 EXECUTE format('GRANT USAGE ON SCHEMA business_management TO %I',runtime);
 EXECUTE format('GRANT EXECUTE ON FUNCTION business_management.business_stores() TO %I',runtime);
END $$;

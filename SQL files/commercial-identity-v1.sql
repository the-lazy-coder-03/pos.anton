CREATE FUNCTION business_management.manage_business_store(command_value uuid,business_value uuid,store_value uuid,expected_value bigint,value jsonb) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public,app_security AS $$
DECLARE b public.business; s public.branch; receipt public.business_command_receipt; fingerprint text; who bigint;
 result jsonb; versions jsonb; logical_millis bigint; logical_counter bigint;
BEGIN
 IF NOT business_management.is_business_owner() THEN RAISE EXCEPTION 'Business Owner required' USING ERRCODE='42501'; END IF;
 who:=app_security.actor_customer_id();
 SELECT * INTO b FROM public.business WHERE singleton FOR UPDATE;
 IF b.business_id IS DISTINCT FROM business_value OR command_value IS NULL THEN RAISE EXCEPTION 'Invalid business scope' USING ERRCODE='42501'; END IF;
 IF value IS NULL OR jsonb_typeof(value)<>'object' OR value - ARRAY['name','code','address','phone','email','active','archived','openingHours','configuration'] <> '{}'::jsonb
 OR length(trim(value->>'name')) NOT BETWEEN 1 AND 200 OR length(trim(value->>'code')) NOT BETWEEN 1 AND 40
 OR value->>'name' IS NULL OR value->>'code' IS NULL
 OR COALESCE(length(value->>'address'),0)>2000 OR COALESCE(length(value->>'phone'),0)>64 OR COALESCE(length(value->>'email'),0)>254
 OR value ? 'active' AND jsonb_typeof(value->'active')<>'boolean'
 OR value ? 'archived' AND jsonb_typeof(value->'archived')<>'boolean'
 OR value ? 'configuration' AND jsonb_typeof(value->'configuration')<>'object'
 OR value ? 'openingHours' AND jsonb_typeof(value->'openingHours')<>'object'
 THEN RAISE EXCEPTION 'Invalid store configuration' USING ERRCODE='23514'; END IF;
 fingerprint:=encode(public.digest(jsonb_build_array(business_value,store_value,expected_value,value)::text,'sha256'),'hex');
 SELECT * INTO receipt FROM public.business_command_receipt WHERE command_id=command_value;
 IF FOUND THEN
  IF receipt.actor_id<>who OR receipt.digest<>fingerprint THEN RAISE EXCEPTION 'Command reused' USING ERRCODE='23505'; END IF;
  RETURN receipt.result;
 END IF;
 IF store_value IS NULL THEN
  IF expected_value IS NOT NULL THEN RAISE EXCEPTION 'New store cannot have revision' USING ERRCODE='23514'; END IF;
  INSERT INTO public.branch(name,business_id,code,address,phone,email,active,archived,configuration,opening_hours,created_at,updated_at)
  VALUES(trim(value->>'name'),business_value,trim(value->>'code'),COALESCE(value->>'address',''),COALESCE(value->>'phone',''),COALESCE(value->>'email',''),
   COALESCE((value->>'active')::boolean,true) AND NOT COALESCE((value->>'archived')::boolean,false),COALESCE((value->>'archived')::boolean,false),
   COALESCE(value->'configuration','{}'),COALESCE(value->'openingHours','{}'),clock_timestamp(),clock_timestamp()) RETURNING * INTO s;
 ELSE
  SELECT * INTO s FROM public.branch WHERE store_uuid=store_value AND business_id=business_value FOR UPDATE;
  IF NOT FOUND OR expected_value IS NULL OR s.revision<>expected_value THEN RAISE EXCEPTION 'Store revision conflict' USING ERRCODE='40001'; END IF;
  UPDATE public.branch SET name=trim(value->>'name'),code=trim(value->>'code'),address=COALESCE(value->>'address',s.address),
   phone=COALESCE(value->>'phone',s.phone),email=COALESCE(value->>'email',s.email),
   active=COALESCE((value->>'active')::boolean,s.active) AND NOT COALESCE((value->>'archived')::boolean,s.archived),
   archived=COALESCE((value->>'archived')::boolean,s.archived),configuration=COALESCE(value->'configuration',s.configuration),
   opening_hours=COALESCE(value->'openingHours',s.opening_hours),revision=revision+1,updated_at=clock_timestamp()
   WHERE store_uuid=store_value RETURNING * INTO s;
 END IF;
 result:=to_jsonb(s);
 INSERT INTO public.business_command_receipt VALUES(command_value,who,fingerprint,result,clock_timestamp());
 INSERT INTO public.business_management_audit(event_id,command_id,actor_id,action,store_id)
 VALUES(gen_random_uuid(),command_value,who,CASE WHEN store_value IS NULL THEN 'STORE_CREATED' ELSE 'STORE_CHANGED' END,s.store_uuid);
 logical_millis:=GREATEST(b.clock_millis,floor(extract(epoch from clock_timestamp())*1000)::bigint);
 logical_counter:=CASE WHEN logical_millis=b.clock_millis THEN b.clock_counter+1 ELSE 0 END;
 UPDATE public.business SET clock_millis=logical_millis,clock_counter=logical_counter WHERE singleton;
 SELECT jsonb_object_agg(k,jsonb_build_object('utcMillis',logical_millis,'counter',logical_counter,'sourceId',b.source_id,'operationId',command_value)) INTO versions FROM jsonb_object_keys(value) k;
 INSERT INTO public.pos_configuration_change(change_id,business_id,store_id,entity_type,entity_id,operation,fields,versions)
 VALUES(command_value,business_value,s.store_uuid,'STORE',s.store_uuid,CASE WHEN store_value IS NULL THEN 'CREATE' ELSE 'UPDATE' END,value,versions);
 RETURN result;
END $$;
REVOKE ALL ON FUNCTION business_management.manage_business_store(uuid,uuid,uuid,bigint,jsonb) FROM PUBLIC;
DO $$ DECLARE runtime text:=current_setting('app.runtime_role'); BEGIN
 EXECUTE format('GRANT EXECUTE ON FUNCTION business_management.manage_business_store(uuid,uuid,uuid,bigint,jsonb) TO %I',runtime);
END $$;
